// Builds the English journal next to the German one and lists text that is still German.
//   public/journal/journal.js   -> public/journal/journal.en.js     (scripts/i18n/journal.en.txt)
//   public/journal/backtest.js  -> public/journal/backtest.en.js    (scripts/i18n/backtest.en.txt)
//   app/(journal)/app/markup.js -> app/(journal)/app/markup.en.js   (scripts/i18n/journal.en.txt)
// usage: node scripts/i18n/build.js [--report]   (exits with 1 when German text is left)
const fs = require('fs');
const path = require('path');
const { apply } = require('./apply');
const { findRuns } = require('./runs');

const APP = path.join(__dirname, '..', '..');
const at = (...p) => path.join(APP, ...p);
const LANG_J = at('scripts/i18n/journal.en.txt'), LANG_B = at('scripts/i18n/backtest.en.txt');
const REPORT = process.argv.includes('--report');

// German words that never appear in the English UI
const DE = /[äöüßÄÖÜ„]|\b(der|die|das|dem|den|des|und|oder|nicht|ist|sind|ein|eine|einen|einem|mit|für|auf|von|zum|zur|im|du|dein|deine|deinen|deinem|dir|dich|wird|werden|kann|kannst|noch|keine|kein|bei|nach|vor|aus|über|unter|wie|wenn|dann|schon|nur|alle|alles|Konto|Konten|Seite|Tage|Woche|Monat|Speichern|Löschen|Schließen|Abbrechen|Zurück|Weiter|Fertig|Heute|eintragen|bearbeiten|gespeichert|gelöscht|Ergebnis|Datum|Uhrzeit|Richtung|Notizen|Titel|Kategorie|Hilfe|Einstellungen|Abo|Anmelden|Abmelden|Kerze|Kerzen|Markt|Märkte|Zeichnung|Zeichnungen|Linie|Linien|Farbe|Hintergrund|Schrift|Größe|Kontostand|Gewinnziel|Verlust|Tagesverlust|Kommission|Hebel|Regeln|Kosten|Kontrakte|Kontrakten|Zeitzone|Datei|Dateien|Daten|Kursdaten|Anleitung|Schritt|Punkte|Punkt|Stunde|Stunden|Minuten|Täglich|Uhr|KW|Strg|Entf|Umschalt|Leertaste|z\. B\.|bzw|bis|je|zu|als|sich|ihn|sie|wir|uns|euch|hier|dort|jetzt|sofort|immer|gerade|sehr|mehr|weniger|neue|neuen|neues|neu|alt|alte|eigene|eigenen|ohne|beim|vom|ins|um|zwischen|zurück|weiter)\b/;
const CODEISH = /^[\w$.#:\-\/\[\]()="',*>+~%@{}| ]*$/;     // selectors, keys, CSS

function german(src, html) {
  const out = [];
  for (const r of findRuns(src, html)) {
    const k = r.key;
    if (!/[A-Za-zÄÖÜäöüß]{2}/.test(k)) continue;
    if (!/[äöüßÄÖÜ„]/.test(k) && CODEISH.test(k) && !/\s/.test(k.trim())) continue;
    if (!/\s/.test(k) && /^(@media|\(|\.|#|\[|var\(|rgba?\(|translate|scale|cubic|M\d)/.test(k)) continue;
    if (DE.test(k.replace(/\$\{[^}]*\}/g, ' '))) out.push(k);   // the words, not the code inside ${…}
  }
  return [...new Set(out)];
}

function readMarkup(file) {
  const s = fs.readFileSync(file, 'utf8');
  return JSON.parse(s.slice(s.indexOf('"'), s.lastIndexOf('"') + 1));
}

const jobs = [
  { name: 'journal.en.js', lang: [LANG_J], src: at('public/journal/journal.js'), out: at('public/journal/journal.en.js') },
  { name: 'backtest.en.js', lang: [LANG_B], src: at('public/journal/backtest.js'), out: at('public/journal/backtest.en.js') },
  { name: 'markup.en.js', lang: [LANG_J], markup: at('app/(journal)/app/markup.js'), out: at('app/(journal)/app/markup.en.js'), html: true },
];
const used = new Map();     // lang file -> Set of used keys
let left = 0;
for (const j of jobs) {
  const src = j.markup ? readMarkup(j.markup) : fs.readFileSync(j.src, 'utf8');
  const r = apply(j.lang, src, !!j.html, { code: !j.markup });   // code swaps are for the scripts
  const all = new Set(r.unused);
  for (const f of j.lang) {
    if (!used.has(f)) used.set(f, { all: null, unused: all });
    else { const u = used.get(f).unused; for (const k of [...u]) if (!all.has(k)) u.delete(k); }
  }
  if (j.markup) fs.writeFileSync(j.out, '// generated by scripts/i18n/build.js: the English journal markup\nexport const MARKUP_EN = ' + JSON.stringify(r.out) + ';\n');
  else fs.writeFileSync(j.out, r.out);
  const g = german(r.out, !!j.html);
  left += g.length;
  console.log(`${j.name}: ${r.edits} runs translated, ${g.length} German runs left`);
  if (REPORT && g.length) console.log(g.map((k) => '  ' + JSON.stringify(k.length > 160 ? k.slice(0, 160) + '…' : k)).join('\n'));
}
for (const [f, { unused }] of used) {
  if (unused.size) console.log(`${path.basename(f)}: ${unused.size} pairs matched nothing` + (REPORT ? ':\n' + [...unused].map((k) => '  ' + JSON.stringify(k)).join('\n') : ''));
}
if (left) process.exitCode = 1;
